'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const noc=fs.readFileSync(path.join(root,'noc-table.js'),'utf8');
const setup=fs.readFileSync(path.join(root,'install-nightshift-nocform.ps1'),'utf8');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.match(noc,/id="openNocBuilder"/);
assert.match(noc,/id="openNocExternalForm"/);
assert.match(noc,/href="nightshifthub-nocform:\/\/open"/);
assert.match(noc,/เปิด Table Builder/);
assert.match(noc,/เปิด NOC External Form/);
assert.match(html,/<script src="\.\/noc-table\.js"><\/script>/);
assert.match(setup,/HKCU:\\Software\\Classes\\/);
assert.match(setup,/OPEN_NOC_FORM\.cmd/);
assert.match(setup,/NOC_External_Form\.ps1/);
assert.match(setup,/Start-Process -FilePath \$cmd -WorkingDirectory \$folder/);
assert.match(setup,/Read-Host 'Type YES to install/);
assert.match(setup,/Copy-Item -LiteralPath \$SourceCmd/);
assert.match(setup,/Copy-Item -LiteralPath \$sourcePs/);
assert.match(setup,/Check-HandlerOwnership/);
assert.doesNotMatch(setup,/Invoke-Expression|DownloadString|Invoke-WebRequest|Start-BitsTransfer/i);
assert.doesNotMatch(setup,/\$command=[^\n]*%1/);
assert.doesNotMatch(noc,/NOC_External_Form\.ps1/);
assert.ok(!fs.existsSync(path.join(root,'NOC_External_Form.ps1')),'Private script must NOT be published');
assert.ok(!fs.existsSync(path.join(root,'OPEN_NOC_FORM.cmd')),'Private CMD must NOT be published');
console.log('PASS: Night Shift Hub NOC External Form button and local installer static contract');
